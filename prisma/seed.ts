async function main() {
  // Security invariant: Seed ONLY public showcase 3D models. NEVER seed demo user accounts.
  for (const item of COMMUNITY_SHOWCASE_MODELS) {
    const { meshData, vertices, faces } = synthesizeProceduralMesh({
      prompt: item.prompt,
      category: item.category,
      generationMode: item.generationMode,
      topology: item.topology,
      targetPolycount: item.targetPolycount,
      textureQuality: item.textureQuality,
      hasPbr: true,
      isSegmented: item.isSegmented,
      isRigged: item.isRigged,
    });

    await prisma.asset3D.upsert({
      where: { id: item.id },
      create: {
        id: item.id,
        ownerId: null,
        ownerName: item.ownerName,
        name: item.name,
        prompt: item.prompt,
        category: item.category,
        generationMode: item.generationMode,
        inputMode: 'TEXT',
        aiModel: item.aiModel,
        topology: item.topology,
        vertices,
        faces,
        targetPolycount: item.targetPolycount,
        hasTexture: true,
        textureQuality: item.textureQuality,
        hasPbr: true,
        hasSmartUv: item.generationMode === 'SMART_MESH',
        isSegmented: item.isSegmented,
        isRigged: item.isRigged,
        activeAnimation: item.activeAnimation,
        privacy: 'PUBLIC',
        featured: item.featured,
        likesCount: item.likesCount,
        viewsCount: item.viewsCount,
        meshDataJson: JSON.stringify(meshData),
      },
      update: {
        name: item.name,
        prompt: item.prompt,
        meshDataJson: JSON.stringify(meshData),
      },
    });
  }

  console.log(`Seeded ${COMMUNITY_SHOWCASE_MODELS.length} public showcase 3D models (0 demo user accounts created).`);
}

main()
  .catch((err) => {
    console.error(err);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
